import "server-only";

import { createClient as createSupabaseClient } from "@supabase/supabase-js";

import type { Database } from "@/types/database.types";

/**
 * Privileged client using the secret key -- bypasses RLS entirely.
 * Only use for trusted server-side operations (e.g. admin-created staff
 * accounts via auth.admin.createUser). Never import this into a Client
 * Component or expose its result directly to the browser.
 */
export function createAdminClient() {
  return createSupabaseClient<Database>(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.SUPABASE_SECRET_KEY!,
    {
      auth: {
        autoRefreshToken: false,
        persistSession: false,
      },
    },
  );
}
